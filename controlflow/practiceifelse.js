// GRADE SYSTEM

let marks = 85;
let name = "deepanshu";

if(marks >= 90){
    console.log(`A grade ${name}`)
}
else if(marks >= 80){
    console.log(`B grade ${name}`)
}
else if(marks >= 75){
    console.log(`C grade ${name}`)
}
else if(marks >= 50){
    console.log(`D grade ${name}`)
}
else{
    console.log(`fail ${name} sorry`);
}